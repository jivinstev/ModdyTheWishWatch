package com.moddingfromamod.pack;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.moddingfromamod.datapack.VanillaCarrier;
import com.moddingfromamod.item.IconSprites;
import com.moddingfromamod.item.WishIcons;
import com.moddingfromamod.vanilla.AtomLibrary;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * <b>The jar's copy of the carrier's bindings is the runtime pack's, namespace aside.</b>
 *
 * <p>A client WITH the mod is never pushed the item pack ({@code ItemPackService.offerTo} refuses
 * one), so it draws every wished thing, Moddy and every atom-rig cube out of the JAR's own
 * {@code assets/minecraft/items/leather_horse_armor.json} (an old stack, by number — the ♻️ SHIM in
 * {@code docs/COMPAT_SHIMS.md}) and {@code assets/wishpack/items/icon/<name>.json} (a new stack, by
 * name). Those files are generated by {@code tools/gen-carrier-model.py}; the pushed pack's are
 * written at runtime by {@link VanillaItemPack}. Two emitters, so this holds the generated files to
 * be <b>exactly</b> what the runtime writes for the same bindings, with the pack's {@code wishpack}
 * namespace read as the mod's — a missing entry, a moved number or a differently-tinted node is one
 * icon drawing wrong on one route, months later, with every other gate green.
 *
 * <p>Until this test compared the jar's pre-1.21.4 {@code overrides} carrier model against
 * {@code wish_item.json}'s overrides, and the generator derived the {@code items/} definitions from
 * that table. refuses every client that could read an {@code overrides} table, so the table,
 * its {@code _flat} one-tint twins and {@code wish_item.json}'s own overrides are gone; the
 * generator reads the runtime's binding table instead ({@code IconSprites} + {@code AtomLibrary}).
 */
class CarrierModelDriftTest {

    private static final Path JAR = Path.of("src/main/resources");
    private static final Path CARRIER_DEF = JAR.resolve("assets/minecraft/items/leather_horse_armor.json");
    private static final Path WISH_ITEM_DEF = JAR.resolve("assets/moddingfromamod/items/wish_item.json");

    private static VanillaItemPack.Spec spec() {
        return new VanillaItemPack.Spec(WishPackWriter.BASE_ITEM,
                WishPackWriter.icons("on"), WishPackWriter.atoms("on"));
    }

    /**
     * What the runtime writes, as the jar spells it. Two differences, both about WHERE a model file
     * lives and neither about what is drawn: the pack's namespace is the mod's in the jar, and the
     * pack files every sprite binding under {@code item/wish/} while the jar keeps Moddy, the wand
     * and the bag beside that folder ({@link IconSprites.Sprite#model()}).
     */
    private static JsonElement asJar(String runtimeJson) {
        String s = runtimeJson;
        for (IconSprites.Sprite sprite : IconSprites.bindings()) {
            if (!sprite.model().startsWith("wish/")) {
                s = s.replace("\"" + VanillaItemPack.NAMESPACE + ":item/wish/" + sprite.name() + "\"",
                        "\"moddingfromamod:item/" + sprite.model() + "\"");
            }
        }
        return JsonParser.parseString(s.replace("\"" + VanillaItemPack.NAMESPACE + ":", "\"moddingfromamod:"));
    }

    private static JsonObject read(Path p) throws Exception {
        return JsonParser.parseString(Files.readString(p, StandardCharsets.UTF_8)).getAsJsonObject();
    }

    @Test
    @DisplayName("the jar's carrier range_dispatch is exactly the runtime pack's")
    void theCarrierDefinitionIsTheRuntimes() throws Exception {
        assertTrue(Files.exists(CARRIER_DEF), "the jar ships no carrier definition, so a modded client "
                + "draws every old wished stack as a plain leather horse armour. Run tools/gen-carrier-model.py");
        assertEquals(asJar(VanillaItemPack.itemDefinition(spec())), read(CARRIER_DEF),
                "the jar's carrier definition differs from what the runtime pack writes for the same "
                        + "bindings. Run tools/gen-carrier-model.py");
    }

    @Test
    @DisplayName("every native definition in the jar is exactly the runtime pack's, and there are no others")
    void theNativeDefinitionsAreTheRuntimes() throws Exception {
        Map<String, String> runtime = VanillaItemPack.nativeDefinitions(spec());
        for (Map.Entry<String, String> e : runtime.entrySet()) {
            Path jar = JAR.resolve(e.getKey());
            assertTrue(Files.exists(jar), "the jar has no " + e.getKey() + ", so a modded client draws a "
                    + "stack naming it as the magenta missing model. Run tools/gen-carrier-model.py");
            assertEquals(asJar(e.getValue()), read(jar),
                    e.getKey() + " differs from the runtime pack's. Run tools/gen-carrier-model.py");
        }
        try (var files = Files.list(JAR.resolve("assets/" + NativeItemModels.NAMESPACE + "/items/"
                + NativeItemModels.DIR))) {
            List<String> extra = files.map(p -> JAR.relativize(p).toString().replace('\\', '/'))
                    .filter(p -> !runtime.containsKey(p)).toList();
            assertTrue(extra.isEmpty(), "the jar ships native definitions nothing binds: " + extra);
        }
    }

    @Test
    @DisplayName("Moddy, the anvil's wand, the Wish Bag and every atom cube are in the table")
    void theReservedBindingsAreThere() throws Exception {
        JsonArray entries = read(CARRIER_DEF).getAsJsonObject("model").getAsJsonArray("entries");
        List<Integer> numbers = new ArrayList<>();
        for (JsonElement e : entries) {
            numbers.add(e.getAsJsonObject().get("threshold").getAsInt());
        }
        // A control that the spec under test is not empty, or the equality above proves nothing.
        assertEquals(IconSprites.bindings().size() + AtomLibrary.all().size(), numbers.size());
        for (int n : List.of(VanillaCarrier.WATCH_MODEL_DATA, VanillaCarrier.WISH_WAND_MODEL_DATA,
                VanillaCarrier.WISH_BAG_MODEL_DATA, VanillaCarrier.BACK_ARROW_MODEL_DATA,
                VanillaCarrier.LIGHT_BULB_MODEL_DATA)) {
            assertTrue(numbers.contains(n), "the jar's carrier table has no entry at " + n);
        }
        for (AtomLibrary.Entry atom : AtomLibrary.all()) {
            assertTrue(numbers.contains(atom.customModelData()), "no atom cube at " + atom.customModelData()
                    + " — a modded client draws that box of every atom-rig creature as a magenta cube");
        }
        assertTrue(Files.exists(JAR.resolve("assets/moddingfromamod/textures/item/"
                        + VanillaCarrier.WISH_WAND_ICON + ".png.mcmeta")),
                "the wand's frame strip ships without its animation, so every client draws all "
                        + "eight frames squashed into one slot");
    }

    @Test
    @DisplayName("the mod's own wish item binds the wish band and nothing else, drawn as the carrier draws it")
    void theWishItemBindsTheWishBand() throws Exception {
        JsonObject model = read(WISH_ITEM_DEF).getAsJsonObject("model");
        JsonArray mine = model.getAsJsonArray("entries");
        JsonArray carrier = read(CARRIER_DEF).getAsJsonObject("model").getAsJsonArray("entries");
        List<JsonElement> wishBand = new ArrayList<>();
        for (JsonElement e : carrier) {
            if (e.getAsJsonObject().get("threshold").getAsInt() < VanillaCarrier.WATCH_MODEL_DATA) {
                wishBand.add(e);
            }
        }
        assertEquals(IconSprites.library().size(), wishBand.size());
        assertEquals(wishBand.size(), mine.size(), "wish_item binds a different set than the carrier's wish band");
        for (int i = 0; i < mine.size(); i++) {
            assertEquals(wishBand.get(i), mine.get(i), "wish_item entry " + i + " draws differently");
        }
        assertEquals("moddingfromamod:item/wish_item",
                model.getAsJsonObject("fallback").get("model").getAsString());
    }

    @Test
    @DisplayName("Moddy's number is above every wish icon, so a wish can never reach it")
    void moddysNumberIsOutOfTheWishLibrarysReach() {
        for (WishIcons.Icon icon : WishIcons.all()) {
            assertTrue(icon.id() < VanillaCarrier.WATCH_MODEL_DATA,
                    "wish icon " + icon.name() + " is " + icon.id() + ", at or past Moddy's "
                            + "reserved " + VanillaCarrier.WATCH_MODEL_DATA + " — a wished thing "
                            + "that comes back looking like the watch you wished WITH is a picture "
                            + "nobody can read. Move the reserve, never the library.");
        }
        for (IconSprites.Sprite s : IconSprites.library()) {
            assertTrue(s.customModelData() < VanillaCarrier.WATCH_MODEL_DATA, s.name());
        }
    }

    /**
     * <b>: the jar ships no pre-1.21.4 binding at all.</b> The runtime pack's twin is
     * {@code ItemPackBindingTest.thePackCarriesNoOverridesAnywhere}. The server refuses every
     * client older than 1.21.4 at join, and 1.21.4 ignores an {@code overrides} array, so
     * one appearing in the jar again is a second copy of the binding with no reader and no oracle.
     */
    @Test
    @DisplayName("#1596: no json the jar ships carries an `overrides` array, and there is no carrier model or _flat twin")
    void theJarCarriesNoOverridesAnywhere() throws Exception {
        List<String> withOverrides = new ArrayList<>();
        List<String> flat = new ArrayList<>();
        int scanned = 0;
        try (var walk = Files.walk(JAR.resolve("assets"))) {
            for (Path f : walk.filter(Files::isRegularFile).toList()) {
                String name = f.getFileName().toString();
                if (f.toString().replace('\\', '/').contains("/wish/") && name.matches("[a-z0-9_]+_flat\\.(json|png)")) {
                    flat.add(JAR.relativize(f).toString());
                }
                if (!name.endsWith(".json")) {
                    continue;
                }
                scanned++;
                if (hasKey(JsonParser.parseString(Files.readString(f, StandardCharsets.UTF_8)), "overrides")) {
                    withOverrides.add(JAR.relativize(f).toString());
                }
            }
        }
        assertTrue(scanned > 200, "the scan read only " + scanned + " json files — it is looking in the wrong place");
        assertTrue(withOverrides.isEmpty(), "the jar ships a pre-1.21.4 `overrides` table again, in "
                + withOverrides + ". No admitted client reads one (#1585); bind it in an items/ definition");
        assertFalse(Files.exists(JAR.resolve("assets/minecraft/models/item/" + WishPackWriter.BASE_ITEM + ".json")),
                "the jar replaces the carrier's MODEL again; a plain carrier draws vanilla's through the fallback");
        assertTrue(flat.isEmpty(), "the jar ships #1052 `_flat` twins, which only an overrides table bound: " + flat);
        // Self-check: the search fires on a nested key, or a green result means nothing.
        assertTrue(hasKey(JsonParser.parseString("{\"a\":[{\"overrides\":[]}]}"), "overrides"));
    }

    private static boolean hasKey(JsonElement e, String key) {
        if (e.isJsonObject()) {
            for (Map.Entry<String, JsonElement> m : e.getAsJsonObject().entrySet()) {
                if (m.getKey().equals(key) || hasKey(m.getValue(), key)) {
                    return true;
                }
            }
        } else if (e.isJsonArray()) {
            for (JsonElement x : e.getAsJsonArray()) {
                if (hasKey(x, key)) {
                    return true;
                }
            }
        }
        return false;
    }
}
