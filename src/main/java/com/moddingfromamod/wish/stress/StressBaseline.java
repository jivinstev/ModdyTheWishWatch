package com.moddingfromamod.wish.stress;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.moddingfromamod.wish.WishCorpus;

/**
 * <b>The corpus ratchet: coverage may go up, never quietly down.</b>
 *
 * <p> stage 6. A gate that runs "however many cases happen to be claimed" can lose coverage
 * without anyone noticing — delete a harness, mistype a kind, and the suite still passes, just over
 * fewer things. That is the same failure the keystone prevents for *unclaimed* cases, one level up:
 * the keystone catches a case nobody runs, this catches a whole KIND quietly falling out.
 *
 * <p>Deliberately a floor, expressed in code rather than a JSON file. The numbers are small, they
 * change with the corpus, and a committed baseline file for them would rot into a thing people
 * update reflexively. What must not happen is a kind going to zero or the claimed set shrinking —
 * so that, and only that, is asserted.
 */
public final class StressBaseline {

    /**
     * The kinds that must always be stressed, and the minimum cases each must contribute.
     *
     * <p>Raise these when the corpus grows; lowering one requires deleting a line, which is a
     * visible act in a diff rather than a number quietly drifting down.
     */
    public static final Map<String, Integer> FLOOR = new LinkedHashMap<>(Map.of(
            // Raised from 15. The corpus has held 84 buildings cases for a while; the
            // floor stayed at 15 because the buildings gate was a tautology, so 69 of them were
            // being carried rather than checked and there was nothing to protect.
            "buildings", 80,
            // Raised from 15: the 23 creature EVAL prompts now run here too, having sat outside
            // the loader for their whole life because they carry tier/sourcing rather than the
            // shared schema.
            "creatures", 90,
            "composite", 5,
            // "machines" (126) and "trains" (14) went with Create; their corpus files are
            // parked on branch parked/create-trains-mc1.21.1.
            "datapacks", 2,
            // The pictures corpus, generated by tools/gen-picture-corpus.py.
            "pictures", 13,
            // a building and a creature from one wish, the creature on a named spot.
            "placement", 6));

    private StressBaseline() {
    }

    /** How the current corpus measures against the floor. Empty means the ratchet holds. */
    public static List<String> regressions(List<WishCorpus.Case> all) {
        java.util.List<String> out = new java.util.ArrayList<>();
        FLOOR.forEach((kind, min) -> {
            if (StressRegistry.forKind(kind) == null) {
                out.add("kind '" + kind + "' has no harness any more — it used to be stressed and "
                        + "now is not, which is a coverage regression the suite would otherwise "
                        + "report as a pass");
                return;
            }
            long have = all.stream().filter(c -> kind.equals(c.kind())).count();
            if (have < min) {
                out.add("kind '" + kind + "' is down to " + have + " case(s), below the floor of "
                        + min + ". Coverage may go up freely; going down is a deliberate act and "
                        + "must be a visible edit to StressBaseline.FLOOR.");
            }
        });
        return out;
    }
}
