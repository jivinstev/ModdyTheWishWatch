package com.moddingfromamod.wish;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * <b>Only characters a stock client can draw</b>.
 *
 * <p>The owner's stock 26.3 client showed the agent's "☀️🆕" as boxes. The guess — "emoji are not
 * in Minecraft's font" — is wrong, and measuring said so: ☀ is in the bitmap font and 🆕 is in
 * unifont. The box was <b>U+FE0F</b>, the invisible "emoji presentation" selector that rides
 * behind ☀ in "☀️". Unifont draws every format and control code point as a dashed square with its
 * name inside ("VS16"), and Minecraft renders that square. Our own strings carried the same
 * selector ("🏗️", "↩️ undo", "❤️ hearts") and drew the same box. And 🆕 IS a glyph — a square
 * with "NEW" three pixels tall inside it — which at chat size reads as the same box, so the
 * squared-letter emoji are dropped too (photographed on stock 1.21.1 and 1.21.4).
 *
 * <p>So the rule is not "no emoji", it is a list: {@code glyphs/stock-client.ranges}, generated by
 * {@code tools/stock-glyph-coverage.py} from Mojang's own font assets, is every code point that
 * EVERY supported stock client (1.21.1, 1.21.4, 26.2, 26.3) draws as a real glyph. Anything else —
 * a dashed control square, or a code point no font has (the missing-glyph box) — is dropped. A
 * newline is kept; chat breaks lines on it.
 *
 * <p>Pure and Minecraft-free. {@link #clean} returns the SAME string instance when nothing
 * changes, so the common case (plain words) allocates nothing.
 */
public final class ChildGlyphs {

    private static final String RESOURCE = "/glyphs/stock-client.ranges";

    /** Sorted, non-overlapping inclusive ranges, as parallel arrays for a binary search. */
    private static final int[] FROM;
    private static final int[] TO;

    static {
        List<int[]> ranges = load();
        FROM = new int[ranges.size()];
        TO = new int[ranges.size()];
        for (int i = 0; i < ranges.size(); i++) {
            FROM[i] = ranges.get(i)[0];
            TO[i] = ranges.get(i)[1];
        }
    }

    private ChildGlyphs() {
    }

    /** How many ranges were loaded — zero means the table is missing, which a test refuses. */
    static int rangeCount() {
        return FROM.length;
    }

    /** True if every supported stock client draws this code point as a real glyph. */
    public static boolean drawable(int codePoint) {
        if (codePoint == '\n') {
            return true;
        }
        if (codePoint >= 0x20 && codePoint <= 0x7E) {
            return true;                  // the fast path, and true even if the table failed
        }
        int lo = 0;
        int hi = FROM.length - 1;
        while (lo <= hi) {
            int mid = (lo + hi) >>> 1;
            if (codePoint < FROM[mid]) {
                hi = mid - 1;
            } else if (codePoint > TO[mid]) {
                lo = mid + 1;
            } else {
                return true;
            }
        }
        // AN EMPTY TABLE FAILS OPEN. A packaging fault must not blank every word Moddy says; the
        // unit test is what refuses a missing table.
        return FROM.length == 0;
    }

    /**
     * {@code text} with every code point a stock client cannot draw removed, and any run of spaces
     * that leaves behind collapsed. The same instance when nothing needed removing.
     */
    public static String clean(String text) {
        if (text == null || text.isEmpty()) {
            return text;
        }
        int n = text.length();
        int i = 0;
        while (i < n) {
            int cp = text.codePointAt(i);
            if (!drawable(cp)) {
                break;
            }
            i += Character.charCount(cp);
        }
        if (i == n) {
            return text;
        }
        StringBuilder sb = new StringBuilder(n);
        sb.append(text, 0, i);
        boolean dropped = false;
        while (i < n) {
            int cp = text.codePointAt(i);
            i += Character.charCount(cp);
            if (!drawable(cp)) {
                dropped = true;
                continue;
            }
            // "sun ☀️ 🆕" losing a glyph must not leave "sun  " with a double space.
            if (cp == ' ' && dropped && sb.length() > 0 && sb.charAt(sb.length() - 1) == ' ') {
                continue;
            }
            sb.appendCodePoint(cp);
        }
        // Only spaces the removal CREATED are trimmed; ones the sender wrote on purpose stay.
        String out = sb.toString();
        if (!Character.isWhitespace(text.charAt(0))) {
            out = out.stripLeading();
        }
        if (!Character.isWhitespace(text.charAt(text.length() - 1))) {
            out = out.stripTrailing();
        }
        return out;
    }

    /**
     * Clean, IN PLACE, every argument of this tool call that a child reads — the fields
     * {@code SafetyTextSweep.FIELDS} names, which is the one list of them. Returns how many strings
     * changed.
     *
     * <p><b>Rewritten, not refused — the opposite of the safety sweep, on purpose.</b> That sweep
     * refuses because silently rewriting a WORD leaves the agent believing it said the other one.
     * Nothing here is a word: a variation selector or a joiner is invisible in the agent's own
     * transcript, so there is nothing for it to learn from a refusal and a round trip (~6 s) to
     * delete a code point it cannot see would be pure cost. The only change a child can notice is
     * a box that is no longer there.
     *
     * <p>{@code run_command}'s commands are cleaned whole: nothing in a command's syntax needs a
     * non-drawable code point, and the text inside a {@code tellraw} is the part he reads.
     */
    public static int cleanArgs(String tool, com.google.gson.JsonObject args) {
        if (tool == null || args == null) {
            return 0;
        }
        int changed = 0;
        for (var field : com.moddingfromamod.safety.SafetyTextSweep.FIELDS) {
            if (!field.tool().equals(tool) || !args.has(field.arg())) {
                continue;
            }
            var el = args.get(field.arg());
            switch (field.shape()) {
                case STRING, COMMANDS -> {
                    if (el.isJsonPrimitive() && el.getAsJsonPrimitive().isString()) {
                        changed += replace(args, field.arg(), el.getAsString());
                    } else if (el.isJsonArray() && field.shape()
                            == com.moddingfromamod.safety.SafetyTextSweep.Shape.COMMANDS) {
                        changed += cleanArray(el.getAsJsonArray());
                    }
                }
                case STRING_ARRAY -> {
                    if (el.isJsonArray()) {
                        changed += cleanArray(el.getAsJsonArray());
                    }
                }
                case OBJECT_ARRAY_MEMBER -> {
                    if (el.isJsonArray()) {
                        for (var e : el.getAsJsonArray()) {
                            if (e != null && e.isJsonObject()) {
                                var o = e.getAsJsonObject();
                                var m = o.get(field.member());
                                if (m != null && m.isJsonPrimitive()
                                        && m.getAsJsonPrimitive().isString()) {
                                    changed += replace(o, field.member(), m.getAsString());
                                }
                            }
                        }
                    }
                }
                default -> { }
            }
        }
        return changed;
    }

    private static int replace(com.google.gson.JsonObject o, String key, String value) {
        String cleaned = clean(value);
        if (cleaned.equals(value)) {
            return 0;
        }
        o.addProperty(key, cleaned);
        return 1;
    }

    private static int cleanArray(com.google.gson.JsonArray arr) {
        int changed = 0;
        for (int i = 0; i < arr.size(); i++) {
            var e = arr.get(i);
            if (e != null && e.isJsonPrimitive() && e.getAsJsonPrimitive().isString()) {
                String v = e.getAsString();
                String cleaned = clean(v);
                if (!cleaned.equals(v)) {
                    arr.set(i, new com.google.gson.JsonPrimitive(cleaned));
                    changed++;
                }
            }
        }
        return changed;
    }

    private static List<int[]> load() {
        List<int[]> out = new ArrayList<>();
        try (InputStream in = ChildGlyphs.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                return out;
            }
            BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            String line;
            while ((line = r.readLine()) != null) {
                line = line.strip();
                if (line.isEmpty() || line.startsWith("#")) {
                    continue;
                }
                int dash = line.indexOf('-');
                int a = Integer.parseInt(dash < 0 ? line : line.substring(0, dash), 16);
                int b = dash < 0 ? a : Integer.parseInt(line.substring(dash + 1), 16);
                out.add(new int[] {a, b});
            }
        } catch (Exception e) {
            out.clear();
        }
        return out;
    }
}
