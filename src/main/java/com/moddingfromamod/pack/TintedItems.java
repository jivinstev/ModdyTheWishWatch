package com.moddingfromamod.pack;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

/**
 * <b>A real vanilla item drawn in a Wish Builder colour scheme</b>: one tinted model per offered item, never a
 * model per colour.
 *
 * <p>A Builder tool, weapon or other stock item is the REAL item, so it behaves as vanilla's. To show his
 * scheme on it, the stack also carries {@code minecraft:item_model wishpack:tinted/<item>} and the colour as
 * {@code minecraft:dyed_color}. That definition is vanilla's own (a bow's pull, a crossbow's charge) with each model
 * swapped for ours: a greyscale TINT layer (the head, the blade, the limbs, a whole snowball) that the
 * {@code minecraft:dye} tint multiplies into the colour, and a KEEP layer (a tool's stick, a bow's string) exactly as
 * vanilla drew it. The colour is a number on the stack, so eleven schemes, or any colour, are the same files.
 *
 * <p>{@code dyed_color} is the one channel both editions read: Java's definitions tint by it, and Geyser writes every
 * item's {@code dyed_color} as Bedrock's {@code customColor}, which a DYEABLE custom item (the moddy-atom extension
 * registers one per row here, keyed on the same {@code item_model}) multiplies its icon by.
 *
 * <p>Everything here is generated by {@code tools/gen-tinted-items.py} from the 1.21.8 client jar into
 * {@code assets/wishpack/{items,models/item,textures/item}/tinted/} — in the jar for a modded client, copied byte for
 * byte into the pushed item pack for a stock one ({@code WishPackWriter}) — and its manifest
 * {@code /tinted-items.json}, which this class reads. Pure; {@code TintedItemsTest} checks the files and the scope.
 */
public final class TintedItems {

    private TintedItems() {
    }

    /** The folder under {@code items/} the definitions live in: {@code wishpack:tinted/<item>}. */
    public static final String DIR = "tinted";

    private static volatile JsonObject manifest;

    static JsonObject manifest() {
        JsonObject m = manifest;
        if (m == null) {
            try (InputStream in = TintedItems.class.getResourceAsStream("/tinted-items.json")) {
                if (in == null) {
                    throw new IllegalStateException("tinted-items.json is not on the classpath (tools/gen-tinted-items.py)");
                }
                m = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            } catch (java.io.IOException e) {
                throw new IllegalStateException(e);
            }
            manifest = m;
        }
        return m;
    }

    /** {@code minecraft:diamond_pickaxe} → its id path ({@code diamond_pickaxe}), or null when not a minecraft item. */
    static String path(String baseItem) {
        if (baseItem == null) {
            return null;
        }
        String b = baseItem.trim();
        int bracket = b.indexOf('[');
        if (bracket >= 0) {
            b = b.substring(0, bracket);
        }
        if (!b.contains(":")) {
            b = "minecraft:" + b;
        }
        return b.startsWith("minecraft:") ? b : null;
    }

    /** The {@code item_model} a real item is drawn in a colour by, or null when it has no tinted model. */
    public static String modelFor(String baseItem) {
        String id = path(baseItem);
        if (id == null || !manifest().getAsJsonObject("items").has(id)) {
            return null;
        }
        return VanillaItemPack.NAMESPACE + ":" + DIR + "/" + id.substring("minecraft:".length());
    }

    /** The real items that have a tinted model, as full ids. */
    public static List<String> items() {
        return new ArrayList<>(manifest().getAsJsonObject("items").keySet());
    }

    /** Offered by the Builder and deliberately NOT tinted: stock id → why (the trident: a special renderer in the hand). */
    public static Map<String, String> notTinted() {
        Map<String, String> out = new LinkedHashMap<>();
        for (Map.Entry<String, JsonElement> e : manifest().getAsJsonObject("not_tinted").entrySet()) {
            out.put(e.getKey(), e.getValue().getAsString());
        }
        return Collections.unmodifiableMap(out);
    }

    /** Every generated file, relative to {@code assets/wishpack/} — what the item pack copies. */
    public static List<String> files() {
        List<String> out = new ArrayList<>();
        manifest().getAsJsonArray("files").forEach(f -> out.add(f.getAsString()));
        return out;
    }

    /**
     * The colour, as a give line spells it on 1.21.8 ({@code compat.ItemSyntax}): a bare number, and hidden from the
     * tooltip, because on a real item "Dyed" is a line about leather and not about his pickaxe. Only the carrier route
     * writes another {@code tooltip_display}, and a real item never takes it, so the component appears once.
     */
    public static String dyedColor(int rgb) {
        return com.moddingfromamod.compat.ItemSyntax.dyedColor(rgb & 0xFFFFFF) + ","
                + com.moddingfromamod.compat.ItemSyntax.hideLines("minecraft:dyed_color");
    }
}
