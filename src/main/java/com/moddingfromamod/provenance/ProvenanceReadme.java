package com.moddingfromamod.provenance;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Writes a self-contained {@code README.md} into the published {@code wishes/} folder of a Mod Repo.
 *
 * <p><b>Why:</b> modding-from-a-mod is an <i>optional</i> dependency — someone (or some Claude) may
 * open the Mod Repo without the engine installed and still need to understand what {@code wishes/}
 * is. So everything published there must be self-describing AND point back to the parent project that
 * produced it. This is the "published content is self-explaining + names its producer" principle from
 * the Mod Repo's {@code docs/REPO_LAYERING.md}.
 *
 * <p>The content is deterministic, so re-writing it on every publish causes no git churn; when the
 * engine updates the template, the next publish refreshes it.
 */
public final class ProvenanceReadme {

    /** Where the parent engine lives, so the published folder can point home. */
    public static final String PARENT_NAME = "modding-from-a-mod";
    public static final String PARENT_MODID = "moddingfromamod";
    public static final String PARENT_URL = "https://github.com/jivinstev/ModdyTheWishWatch";

    private static final String README = String.join("\n",
            "# wishes/ — published by " + PARENT_NAME,
            "",
            "This folder was generated by **" + PARENT_NAME + "** (mod id `" + PARENT_MODID + "`), an",
            "OPTIONAL engine that grants in-game \"wishes\" and records each one here as a durable,",
            "upgradable artifact. Engine / source: " + PARENT_URL,
            "",
            "**You do NOT need " + PARENT_NAME + " installed to read or use this folder.** Everything",
            "here is self-contained data. If the engine isn't present, these are simply files that",
            "describe features which were authored via wishes — and enough context to rebuild or",
            "upgrade them into real (Java) mod code.",
            "",
            "## Layout",
            "",
            "```",
            "wishes/<kind>/<id>/",
            "    manifest.json     the wish(es) that produced this artifact (its provenance)",
            "    <artifact bits>   e.g. template.json  (datapacks keep their bits in wish-datapacks/<id>/)",
            "```",
            "",
            "- **kind** — datapack, template, and later species / build / contraption / train.",
            "- **id** — the artifact's stable name.",
            "",
            "## manifest.json fields",
            "",
            "- `id`, `kind` — identity.",
            "- `intent` — the FIRST wish (the goal it was built to satisfy). This is the human intent.",
            "- `refinements` — later wishes that tuned it, in order.",
            "- `createdMs` — when first published (epoch millis).",
            "- `artifactRef` — where the artifact's bits live (e.g. `wish-datapacks/<id>`).",
            "",
            "## Why this exists",
            "",
            "So a wish-granted feature can later be **upgraded into a real Java mod construct** with both",
            "the precise inspiration (the prompts) and an objective intent to test the mod against. See",
            "the parent project's `docs/REPO_LAYERING.md` and `docs/WISH_GLOSSARY.md` (in " + PARENT_NAME + ")",
            "for the full design and vocabulary.",
            "",
            "*Auto-generated by " + PARENT_NAME + " on publish; edits will be overwritten.*",
            "");

    private ProvenanceReadme() {
    }

    /** Ensure {@code <wishesDir>/README.md} exists and is current. Best-effort; never throws. */
    public static void ensure(Path wishesDir) {
        if (wishesDir == null) {
            return;
        }
        try {
            Files.createDirectories(wishesDir);
            Path readme = wishesDir.resolve("README.md");
            byte[] want = README.getBytes(StandardCharsets.UTF_8);
            // Only write when different, so publishing doesn't rewrite an identical file repeatedly.
            if (!Files.isRegularFile(readme) || !java.util.Arrays.equals(Files.readAllBytes(readme), want)) {
                Files.write(readme, want);
            }
        } catch (Exception ignored) {
            // a missing README must never break a grant
        }
    }

    /** The README text (for tests / backfill tooling). */
    public static String text() {
        return README;
    }
}
