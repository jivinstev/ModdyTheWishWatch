package com.moddingfromamod.content;

import com.google.gson.Gson;
import com.moddingfromamod.ModdingFromAModMod;
import com.moddingfromamod.testing.gt.GameTest;
import com.moddingfromamod.testing.gt.GameTestHolder;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.network.chat.Component;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * <b>The committed snapshot of what is installed is what the game really registers</b>. Gate A and
 * {@code tools/content_search.py} search {@code corpus/apprentice/content-index.json} because a unit test has no
 * registry; this holds that file equal to {@link ContentIndexes#entries()} in a real server, so the tests can never
 * search a different game from the one children play. It writes the live entries to {@code build/content-index.json};
 * after a version bump or a new item, {@code python3 tools/content_search.py accept} copies them over.
 */
@GameTestHolder(ModdingFromAModMod.MODID)
public final class ContentIndexGameTest {

    private ContentIndexGameTest() {
    }

    @GameTest(template = "empty_test")
    public static void theSnapshotIsWhatTheGameRegisters(GameTestHelper helper) {
        try {
            String live = text(ContentIndexes.entries());
            Path repo = repo();
            Files.createDirectories(repo.resolve("build"));
            Files.writeString(repo.resolve("build/content-index.json"), live, StandardCharsets.UTF_8);
            Path snap = repo.resolve("corpus/apprentice/content-index.json");
            String kept = Files.exists(snap) ? Files.readString(snap, StandardCharsets.UTF_8) : "";
            helper.assertTrue(live.equals(kept), Component.literal("corpus/apprentice/content-index.json is not what this "
                    + "game registers (a new item, a renamed block, a version bump). Run: python3 tools/content_search.py accept"));
            helper.assertTrue(ContentIndexes.live().search("honey block", java.util.Set.of(), 3).stream()
                    .anyMatch(h -> h.entry().id().equals("minecraft:honey_block")), Component.literal("the live index finds the honey block"));
            helper.succeed();
        } catch (java.io.IOException e) {
            helper.fail(Component.literal("could not read or write the snapshot: " + e));
        }
    }

    /** One entry a line, [id, kind, name], so a change reads as a diff. */
    static String text(List<ContentIndex.Entry> entries) {
        StringBuilder sb = new StringBuilder("{\"_comment\": \"Every item, block and entity this game registers, with its English "
                + "name. GENERATED by ContentIndexGameTest; refresh with: python3 tools/content_search.py accept\",\n\"entries\": [\n");
        Gson g = new Gson();
        for (int i = 0; i < entries.size(); i++) {
            ContentIndex.Entry e = entries.get(i);
            sb.append(g.toJson(List.of(e.id(), e.kind().name(), e.name()))).append(i + 1 < entries.size() ? ",\n" : "\n");
        }
        return sb.append("]}\n").toString();
    }

    /** The checkout: the first directory up from the run directory that holds corpus/apprentice. */
    static Path repo() {
        Path p = Path.of(System.getProperty("user.dir")).toAbsolutePath();
        while (p != null && !Files.isDirectory(p.resolve("corpus/apprentice"))) {
            p = p.getParent();
        }
        return p == null ? Path.of(".") : p;
    }
}
