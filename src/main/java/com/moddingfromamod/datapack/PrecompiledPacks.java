package com.moddingfromamod.datapack;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.zip.GZIPInputStream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.moddingfromamod.ModdingFromAModMod;

/**
 * <b>Ready-made packs compiled at build time</b>: every Builder and Apprentice power, so no player needs
 * Python for one.
 *
 * <p>The store ({@code precompiled/ready-mades.json.gz}) maps a {@link ReadyMadeSkeleton.Skeleton}'s source to the
 * files the CBScript compiler made from it, compiled under {@link ReadyMadeSkeleton#NAMESPACE} with sentinels where the
 * player's values go. Building a pack is putting the values back: the namespace becomes the feature id, each sentinel
 * its value, the description goes into {@code pack.mcmeta} the way Python's {@code json.dumps} writes it. The result
 * is file for file the zip the compiler would have made ({@code PrecompiledEquivalenceTest}, and
 * {@code -Ptestprops=precompiled=verify} compares the two on every compile).
 *
 * <p>Regenerated by {@code ./tools/precompile-ready-mades.sh}; {@code PrecompiledFingerprintTest} fails Gate A when a
 * template, a catalogue or the bundled compiler changed and it was not run. Pure apart from the classpath read.
 */
public final class PrecompiledPacks {

    static final String RESOURCE = "/precompiled/ready-mades.json.gz";

    private static final org.slf4j.Logger LOGGER = org.slf4j.LoggerFactory.getLogger(ModdingFromAModMod.MODID);

    /** One precompiled skeleton: its files in the compiler's order, sentinels in. */
    record Entry(String source, List<String[]> files) {
    }

    private static volatile Map<String, Entry> store;

    /** Every difference the verify mode found since the last {@link #clearMismatches}: what its GameTest asserts. */
    private static final List<String> MISMATCHES = java.util.Collections.synchronizedList(new ArrayList<>());

    static void mismatch(String what) {
        MISMATCHES.add(what);
    }

    public static List<String> mismatches() {
        synchronized (MISMATCHES) {
            return List.copyOf(MISMATCHES);
        }
    }

    public static void clearMismatches() {
        MISMATCHES.clear();
    }

    private PrecompiledPacks() {
    }

    /** {@code on} (default), {@code off}, or {@code verify} (build both ways and compare). */
    public static String mode() {
        String m = System.getProperty(ModdingFromAModMod.MODID + ".precompiled", "on");
        return m == null ? "on" : m.trim().toLowerCase(java.util.Locale.ROOT);
    }

    public static boolean enabled() {
        return !"off".equals(mode());
    }

    /** The store key: a hash of the skeleton source. */
    public static String key(String skeletonSource) {
        try {
            byte[] d = MessageDigest.getInstance("SHA-256")
                    .digest(skeletonSource.replace("\r\n", "\n").getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(d);
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    static Map<String, Entry> store() {
        Map<String, Entry> s = store;
        if (s == null) {
            synchronized (PrecompiledPacks.class) {
                s = store;
                if (s == null) {
                    s = load();
                    store = s;
                }
            }
        }
        return s;
    }

    private static Map<String, Entry> load() {
        try (InputStream raw = PrecompiledPacks.class.getResourceAsStream(RESOURCE)) {
            if (raw == null) {
                LOGGER.warn("no {} on the classpath: every ready-made needs the CBScript compiler", RESOURCE);
                return Map.of();
            }
            try (InputStream in = new GZIPInputStream(raw)) {
                return parse(new String(in.readAllBytes(), StandardCharsets.UTF_8));
            }
        } catch (IOException | RuntimeException e) {
            LOGGER.warn("could not read {}: {}", RESOURCE, e.toString());
            return Map.of();
        }
    }

    static Map<String, Entry> parse(String json) {
        JsonObject root = JsonParser.parseString(json).getAsJsonObject();
        Map<String, Entry> out = new HashMap<>();
        JsonObject entries = root.getAsJsonObject("entries");
        for (String k : entries.keySet()) {
            List<String[]> files = new ArrayList<>();
            for (var f : entries.getAsJsonObject(k).getAsJsonArray("files")) {
                JsonArray pair = f.getAsJsonArray();
                files.add(new String[] {pair.get(0).getAsString(), pair.get(1).getAsString()});
            }
            JsonObject e = entries.getAsJsonObject(k);
            out.put(k, new Entry(e.has("source") ? e.get("source").getAsString() : "", files));
        }
        return out;
    }

    /** Every skeleton source the store holds, by key: what {@code -Pskeletons=store} recompiles. */
    static Map<String, String> sources() {
        Map<String, String> out = new java.util.TreeMap<>();
        store().forEach((k, e) -> out.put(k, e.source()));
        return out;
    }

    /** Is this skeleton precompiled? */
    public static boolean covers(ReadyMadeSkeleton.Skeleton sk) {
        return sk != null && store().containsKey(key(sk.source()));
    }

    /** How many skeletons the store holds (0 when there is none). */
    public static int size() {
        return store().size();
    }

    /**
     * The pack's files for this make, or null if the skeleton is not precompiled.
     *
     * @param description the description AFTER {@code CbScriptCompiler.withHeader}'s clean-up
     */
    public static Map<String, String> build(String featureId, String description, ReadyMadeSkeleton.Skeleton sk) {
        Entry e = store().get(key(sk.source()));
        return e == null ? null : substitute(e.files(), featureId, description, sk.outputValues());
    }

    /** Put the make's values into compiled skeleton files. Shared with the equivalence test. */
    static Map<String, String> substitute(List<String[]> files, String featureId, String description,
                                          Map<String, String> slots) {
        Map<String, String> all = new LinkedHashMap<>(slots);
        all.put(ReadyMadeSkeleton.NAMESPACE, featureId);
        Map<String, String> out = new LinkedHashMap<>();
        for (String[] f : files) {
            String text = f[1];
            if ("pack.mcmeta".equals(f[0])) {
                text = text.replace(ReadyMadeSkeleton.DESC, pyJsonEscape(description));
            }
            out.put(ReadyMadeSkeleton.substitute(f[0], all), ReadyMadeSkeleton.substitute(text, all));
        }
        return out;
    }

    /** The inside of a JSON string as Python's {@code json.dumps} writes it (ensure_ascii). */
    static String pyJsonEscape(String s) {
        StringBuilder b = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"' -> b.append("\\\"");
                case '\\' -> b.append("\\\\");
                case '\n' -> b.append("\\n");
                case '\r' -> b.append("\\r");
                case '\t' -> b.append("\\t");
                case '\b' -> b.append("\\b");
                case '\f' -> b.append("\\f");
                default -> {
                    if (c < 0x20 || c > 0x7e && c != 0x7f) {
                        b.append(String.format("\\u%04x", (int) c));
                    } else {
                        b.append(c);
                    }
                }
            }
        }
        return b.toString();
    }

    /** Write the files as a datapack zip, in their order. */
    public static void writeZip(Map<String, String> files, Path out) throws IOException {
        if (out.getParent() != null) {
            Files.createDirectories(out.getParent());
        }
        try (OutputStream os = Files.newOutputStream(out); ZipOutputStream zip = new ZipOutputStream(os)) {
            for (var f : files.entrySet()) {
                ZipEntry ze = new ZipEntry(f.getKey());
                ze.setTime(0L);
                zip.putNextEntry(ze);
                zip.write(f.getValue().getBytes(StandardCharsets.UTF_8));
                zip.closeEntry();
            }
        }
    }

    /** Every file in a datapack zip, in order: what the verify mode and the tests compare. */
    public static Map<String, String> readZip(Path zip) throws IOException {
        Map<String, String> out = new LinkedHashMap<>();
        try (var in = new java.util.zip.ZipInputStream(Files.newInputStream(zip))) {
            ZipEntry e;
            while ((e = in.getNextEntry()) != null) {
                if (!e.isDirectory()) {
                    out.put(e.getName(), new String(in.readAllBytes(), StandardCharsets.UTF_8));
                }
            }
        }
        return out;
    }

    /**
     * Record mode ({@code -Ptestprops=precompiled.record=<dir>}): every skeleton a ready-made asked for is written to
     * {@code <dir>/<key>.cbscript}, for {@code ./tools/precompile-ready-mades.sh} to compile into the store.
     */
    static void record(ReadyMadeSkeleton.Skeleton sk) {
        String dir = System.getProperty(ModdingFromAModMod.MODID + ".precompiled.record");
        if (dir == null || dir.isBlank() || sk == null) {
            return;
        }
        try {
            Path d = Path.of(dir);
            Files.createDirectories(d);
            Path f = d.resolve(key(sk.source()) + ".cbscript");
            if (!Files.exists(f)) {
                Files.writeString(f, sk.source(), StandardCharsets.UTF_8);
            }
        } catch (IOException e) {
            LOGGER.warn("precompiled record: could not write a skeleton: {}", e.toString());
        }
    }

    /** The first file the two packs disagree on, and how: for a log line or a failing test. */
    public static String firstDifference(Map<String, String> a, Map<String, String> b) {
        if (!a.keySet().equals(b.keySet()) || !new ArrayList<>(a.keySet()).equals(new ArrayList<>(b.keySet()))) {
            return "files " + a.keySet() + " vs " + b.keySet();
        }
        for (String k : a.keySet()) {
            String x = a.get(k);
            String y = b.get(k);
            if (!x.equals(y)) {
                String[] xl = x.split("\n", -1);
                String[] yl = y.split("\n", -1);
                for (int i = 0; i < Math.max(xl.length, yl.length); i++) {
                    String l1 = i < xl.length ? xl[i] : "<none>";
                    String l2 = i < yl.length ? yl[i] : "<none>";
                    if (!l1.equals(l2)) {
                        return k + " line " + (i + 1) + ":\n  " + l1 + "\n  " + l2;
                    }
                }
            }
        }
        return null;
    }

    /**
     * What the store was compiled FROM: every effect and item template, both catalogues and the CBScript compiler (its vendored tree's digest),
     * hashed by path and content under the source tree's {@code src/main/resources}. The store's manifest records it,
     * and {@code PrecompiledFingerprintTest} fails Gate A when it no longer matches.
     */
    public static String fingerprint(Path resources) throws IOException {
        List<Path> files = new ArrayList<>();
        for (String dir : List.of("effects", "items")) {
            try (var s = Files.list(resources.resolve(dir))) {
                s.filter(f -> f.getFileName().toString().endsWith(".cbs")
                        || f.getFileName().toString().equals("catalogue.json")).forEach(files::add);
            }
        }
        files.sort(java.util.Comparator.comparing(f -> resources.relativize(f).toString().replace('\\', '/')));
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            // The compiler: the vendored tree's digest as its SOURCE records it (CbScriptBundleSourceTest holds the
            // record to the tree). Only the digest, so re-naming the same tree's branch changes nothing.
            String tree = "";
            for (String line : Files.readAllLines(resources.resolve("tools/cbscript.SOURCE"), StandardCharsets.UTF_8)) {
                if (line.startsWith("tree-sha256:")) {
                    tree = line.substring("tree-sha256:".length()).strip();
                }
            }
            md.update(("compiler " + tree).getBytes(StandardCharsets.UTF_8));
            md.update((byte) 0);
            for (Path f : files) {
                md.update(resources.relativize(f).toString().replace('\\', '/').getBytes(StandardCharsets.UTF_8));
                md.update((byte) 0);
                md.update(Files.readAllBytes(f));
                md.update((byte) 0);
            }
            return HexFormat.of().formatHex(md.digest());
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    /** For tests: forget the loaded store so a test-written one is read. */
    static void reset() {
        store = null;
    }
}
